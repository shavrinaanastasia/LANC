def lofo(n, mth):
    t = CB[CB.n == n][["fam", "true", mth]].dropna(); out = {}
    for f in FAMS:
        tr, te = t[t.fam != f], t[t.fam == f]
        if not len(te): out[f] = None; continue
        b, a = np.polyfit(np.log(tr.true), np.log(tr[mth]), 1)
        e = np.exp((np.log(te[mth]) - a) / b) / te.true - 1
        out[f] = (np.median(e), np.abs(e).max())
    return out

